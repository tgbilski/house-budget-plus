- **YouTube**: Original content, documentaries, and entertainment (free)
- **Library Apps**: Many libraries offer free streaming through Hoopla or Kanopy
- **Network Apps**: ABC, NBC, CBS, and FOX offer free content with ads

**Savings**: $200-$400/year

