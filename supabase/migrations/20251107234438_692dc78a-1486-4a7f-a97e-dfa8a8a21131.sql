### Calculate the True Value

A contractor who''s $2,000 more expensive but:
- Uses premium materials
- Has a 10-year labor warranty (vs. 1 year)
- Responds immediately to issues
- Has stellar reviews

...might actually be the better deal in the long run.

## Making Your Final Decision

After comparing all quotes and evaluating intangibles:

1. **Eliminate red flags first:** Cross off any contractors with:
   - Missing insurance or licenses
   - Extremely low bids (likely cutting corners)
   - Poor communication
   - High-pressure sales tactics

2. **Compare your top 2-3 contractors:** Look at your comparison chart and see which offer the best combination of price, quality, and intangibles.

3. **Ask final questions:**
   - Request references and actually call them
   - Ask about the specific crew that will work on your home
   - Clarify the payment schedule (never pay everything upfront)
   - Get everything in writing

4. **Trust your research:** You''ve done the legwork. Choose the contractor who scores best overall, not just the cheapest.

## Red Flags to Watch For

Be wary of contractors who:
- Demand large upfront payments (50%+)
- Don''t provide written contracts
- Offer "today only" discounts
- Can''t provide proof of insurance
- Refuse to pull necessary permits
- Have no physical business address
- Push you to use their preferred insurance adjuster

## After You Choose

Once you''ve selected a contractor:
- **Get everything in writing:** Contract, timeline, payment schedule, warranty details
- **Verify insurance again:** Ask for current certificates of insurance
- **Confirm the permit:** Make sure they''re pulling necessary building permits
- **Document everything:** Take before photos, keep all communications and receipts
- **Set clear communication expectations:** How will they update you on progress?

